// Drives the real controls in headless Chromium and reports console errors.
import { chromium } from 'playwright'
const out = process.argv[2] || 'screenshots'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const errs = []
const log = (...a) => console.log('✓', ...a)
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, acceptDownloads: true, permissions: ['clipboard-read', 'clipboard-write'] })
const page = await ctx.newPage()
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()) })
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
await page.keyboard.press('Space') // skip intro
await page.waitForTimeout(800)
if (await page.locator('.intro').count()) throw new Error('intro not skipped')
log('intro skippable')

await page.getByRole('button', { name: 'Boop Zommie' }).click()
log('boop works')

await page.getByRole('button', { name: /sound off/i }).click()
if ((await page.getByRole('button', { name: /sound on/i }).getAttribute('aria-pressed')) !== 'true') throw new Error('sound')
log('sound toggles')

await page.getByRole('button', { name: 'Menu' }).click()
await page.waitForTimeout(1000)
await page.screenshot({ path: `${out}/x-menu.png` })
await page.getByRole('dialog', { name: 'Site menu' }).getByRole('link', { name: /Grow your own/ }).click()
await page.waitForTimeout(2500)
const labTop = await page.evaluate(() => document.getElementById('lab').getBoundingClientRect().top)
if (Math.abs(labTop) > 120) throw new Error('menu nav failed ' + labTop)
log('menu navigates to lab')

await page.getByPlaceholder('Type any name…').fill('Momo')
const hue1 = await page.locator('.slider--hue .mono').textContent()
await page.getByPlaceholder('Type any name…').fill('Momo')
const hue2 = await page.locator('.slider--hue .mono').textContent()
if (hue1 !== hue2 || hue1 === '78°') throw new Error('seeded name ' + hue1)
log('name seeds creature deterministically', hue1)
await page.getByRole('button', { name: 'Copy link' }).click()
const clip = await page.evaluate(() => navigator.clipboard.readText())
if (!clip.includes('#lab/Momo~')) throw new Error('copy link ' + clip)
log('copy link', clip)
const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Save portrait' }).click()])
log('portrait download', dl.suggestedFilename())
await page.waitForTimeout(600)
await page.screenshot({ path: `${out}/x-lab.png` })

// Shared link restores the creature.
const p2 = await ctx.newPage()
await p2.goto(clip, { waitUntil: 'networkidle' })
await p2.waitForTimeout(800)
const restored = await p2.getByPlaceholder('Type any name…').inputValue()
if (restored !== 'Momo') throw new Error('restore ' + restored)
log('shared link restores creature')
await p2.close()

await page.evaluate(() => document.getElementById('breathe').scrollIntoView())
await page.waitForTimeout(800)
await page.getByText('Box', { exact: true }).click()
await page.getByRole('button', { name: 'Start breathing' }).click()
await page.waitForTimeout(4500)
const word = await page.locator('.breathe__word').textContent()
if (word !== 'Hold') throw new Error('breathe phase ' + word)
await page.screenshot({ path: `${out}/x-breathe.png` })
log('box breathing advances to', word)
await page.getByRole('button', { name: 'Pause' }).click()

await page.evaluate(() => document.getElementById('specimens').scrollIntoView())
await page.waitForTimeout(1500)
await page.getByRole('button', { name: 'Adopt into the lab' }).first().click()
await page.waitForTimeout(1500)
if ((await page.getByPlaceholder('Type any name…').inputValue()) !== 'Moss') throw new Error('adopt')
log('adopt loads specimen into lab')

await page.evaluate(() => document.getElementById('stay').scrollIntoView())
await page.waitForTimeout(800)
await page.getByRole('radio', { name: /10/ }).click()
await page.getByRole('button', { name: /Begin a 10-minute session/ }).click()
await page.waitForTimeout(2000)
const t = await page.locator('.session__time').textContent()
const title = await page.title()
await page.screenshot({ path: `${out}/x-session.png` })
log('session running', t, '| title:', title)
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
if (await page.locator('.session').count()) throw new Error('escape close')
log('escape closes session')

// Reduced motion
const rm = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
const rp = await rm.newPage()
rp.on('pageerror', (e) => errs.push('rm pageerror: ' + e.message))
await rp.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
await rp.waitForTimeout(500)
if (await rp.locator('.intro').count()) throw new Error('intro shown under reduced motion')
await rp.evaluate(() => document.getElementById('ritual').scrollIntoView())
await rp.waitForTimeout(300)
await rp.screenshot({ path: `${out}/x-reduced-ritual.png` })
log('reduced motion: no intro, static ritual =', await rp.locator('.ritual--static').count())

console.log('console errors/warnings:', JSON.stringify(errs))
await browser.close()
